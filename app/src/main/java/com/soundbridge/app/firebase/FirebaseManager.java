    /**
     * Starts observing Firebase Realtime Database presence/{uid}/{deviceId} and liveAlerts/{uid}/{deviceId}
     * while a UI screen is active, cleaning up automatically when stopObservingRealtimeState() is called.
     */
    public synchronized void startObservingRealtimeState(RealtimeStateListener listener) {
        this.realtimeStateListener = listener;
        if (rtdbObserverFuture != null && !rtdbObserverFuture.isCancelled()) {
            rtdbObserverFuture.cancel(false);
        }
        if (!isSignedIn() || isBlank(databaseUrl)) {
            return;
        }
        rtdbObserverFuture = rtdbPollExecutor.scheduleWithFixedDelay(this::pollRealtimeDatabaseOnce, 0, 5, TimeUnit.SECONDS);
    }

    public synchronized void stopObservingRealtimeState() {
        this.realtimeStateListener = null;
        if (rtdbObserverFuture != null) {
            rtdbObserverFuture.cancel(false);
            rtdbObserverFuture = null;
        }
    }

    private void pollRealtimeDatabaseOnce() {
        if (!isSignedIn() || isBlank(databaseUrl) || realtimeStateListener == null) return;
        String uid = prefs.getAuthUid();
        String idToken = prefs.getAuthIdToken();
        String deviceId = prefs.getDeviceId();
        try {
            String presUrl = stripTrailingSlash(databaseUrl) + "/presence/" + uid + "/" + deviceId + ".json?auth=" + idToken;
            String liveUrl = stripTrailingSlash(databaseUrl) + "/liveAlerts/" + uid + "/" + deviceId + ".json?auth=" + idToken;

            boolean online = false;
            boolean monitoring = false;
            String latestAlertText = "None";

            Request presReq = new Request.Builder().url(presUrl).get().build();
            try (Response presResp = httpClient.newCall(presReq).execute()) {
                if (presResp.isSuccessful() && presResp.body() != null) {
                    String s = presResp.body().string();
                    if (!isBlank(s) && !"null".equals(s.trim())) {
                        JSONObject obj = new JSONObject(s);
                        online = obj.optBoolean("online", false);
                        monitoring = obj.optBoolean("monitoringActive", false);
                    }
                }
            }

            Request liveReq = new Request.Builder().url(liveUrl).get().build();
            try (Response liveResp = httpClient.newCall(liveReq).execute()) {
                if (liveResp.isSuccessful() && liveResp.body() != null) {
                    String s = liveResp.body().string();
                    if (!isBlank(s) && !"null".equals(s.trim())) {
                        JSONObject obj = new JSONObject(s);
                        String lbl = obj.optString("label", "");
                        double conf = obj.optDouble("confidence", 0.0);
                        if (!lbl.isEmpty()) {
                            latestAlertText = String.format(Locale.US, "%s (%d%%)", lbl, Math.round(conf * 100));
                        }
                    }
                }
            }

            final boolean finalOnline = online;
            final boolean finalMonitoring = monitoring;
            final String finalLatest = latestAlertText;
            mainHandler.post(() -> {
                if (realtimeStateListener != null) {
                    realtimeStateListener.onPresenceAndLiveAlertUpdated(finalOnline, finalMonitoring, finalLatest);
                }
            });
        } catch (Exception ignored) {
        }
    }

    /**
     * Signs out from Firebase and marks RTDB presence offline.
     */
    public void signOut(Runnable onComplete) {
        if (isSignedIn()) {
            updatePresenceInRealtimeDatabase(false, false, -1);
        }
        stopObservingRealtimeState();
        prefs.clearAuthSession();
        if (onComplete != null) {
            mainHandler.post(onComplete);
        }
    }

    /**
     * Deletes user's cloud data in RTDB & Firestore user document and deletes Firebase Auth account.
     */
    public void deleteAccountAndCloudData(CompletionCallback callback) {
        if (!isSignedIn()) {
            if (callback != null) {
                mainHandler.post(() -> callback.onComplete(false, "No active Firebase account session to delete."));
            }
            return;
        }
        final String uid = prefs.getAuthUid();
        final String idToken = prefs.getAuthIdToken();
        ioExecutor.execute(() -> {
            try {
                if (!isBlank(databaseUrl)) {
                    Request delPres = new Request.Builder()
                            .url(stripTrailingSlash(databaseUrl) + "/presence/" + uid + ".json?auth=" + idToken)
                            .delete().build();
                    try (Response ignored = httpClient.newCall(delPres).execute()) {}

                    Request delLive = new Request.Builder()
                            .url(stripTrailingSlash(databaseUrl) + "/liveAlerts/" + uid + ".json?auth=" + idToken)
                            .delete().build();
                    try (Response ignored = httpClient.newCall(delLive).execute()) {}
                }

                Request delUserDoc = new Request.Builder()
                        .url(getFirestoreBaseUrl() + "/users/" + uid)
                        .addHeader("Authorization", "Bearer " + idToken)
                        .delete().build();
                try (Response ignored = httpClient.newCall(delUserDoc).execute()) {}

                String authDelUrl = "https://identitytoolkit.googleapis.com/v1/accounts:delete?key=" + apiKey;
                JSONObject body = new JSONObject();
                body.put("idToken", idToken);
                Request delAuth = new Request.Builder()
                        .url(authDelUrl)
                        .post(RequestBody.create(body.toString(), JSON_MEDIA))
                        .build();
                try (Response ignored = httpClient.newCall(delAuth).execute()) {}

                prefs.clearAuthSession();
                if (callback != null) {
                    mainHandler.post(() -> callback.onComplete(true, "Cloud data and Firebase Auth session removed."));
                }
            } catch (Exception e) {
                prefs.clearAuthSession();
                if (callback != null) {
                    mainHandler.post(() -> callback.onComplete(false, "Local session cleared; cloud deletion encountered: " + e.getMessage()));
                }
            }
        });
    }

    /**
     * Uses reflection to also hook into com.google.firebase.database.FirebaseDatabase (.info/connected & onDisconnect)
     * when the native Firebase Realtime Database SDK is present at runtime.
     */
    private void tryInvokeNativeRtdbPresence(String uid, String deviceId, boolean online, boolean monitoring, int battery) {
        try {
            Class<?> fbDbClass = Class.forName("com.google.firebase.database.FirebaseDatabase");
            Method getInstance = fbDbClass.getMethod("getInstance");
            Object dbInstance = getInstance.invoke(null);
            Method getRef = fbDbClass.getMethod("getReference", String.class);
            Object presenceRef = getRef.invoke(dbInstance, "presence/" + uid + "/" + deviceId);
            Class<?> dbRefClass = presenceRef.getClass();
            Method onDisconnectMethod = dbRefClass.getMethod("onDisconnect");
            Object onDisconnectObj = onDisconnectMethod.invoke(presenceRef);
            Method childMethod = dbRefClass.getMethod("child", String.class);
            Object onlineChild = childMethod.invoke(presenceRef, "online");
            Method setValMethod = onlineChild.getClass().getMethod("setValue", Object.class);
            setValMethod.invoke(onlineChild, online);
            if (onDisconnectObj != null) {
                Method odChild = onDisconnectObj.getClass().getMethod("removeValue");
                odChild.invoke(onDisconnectObj);
            }
        } catch (Throwable ignored) {
            // Native SDK optional; REST RTDB update handles persistence
        }
    }

