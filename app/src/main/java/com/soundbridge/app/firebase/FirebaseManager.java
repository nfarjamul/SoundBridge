    /**
     * Atomically writes a calibration profile and its immutable audit entry using Firestore :commit,
     * stamping serverUpdatedAt with the server REQUEST_TIME for reliable incremental sync.
     * Firestore Security Rules reject this commit unless the caller is a verified administrator.
     *
     * @return null on success, or a human-readable error message.
     */
    public String commitCalibrationWithAuditSync(GlobalCalibrationProfile profile, CalibrationAuditRecord audit) {
        if (!isSignedIn()) return "Sign in with an administrator account first.";
        if (profile == null) return "Nothing to publish.";
        if (!verifyAdminSync()) return "Administrator privileges required.";
        String token = ensureFreshIdTokenSync();
        try {
            String docRoot = "projects/" + projectId + "/databases/(default)/documents/";
            JSONArray writes = new JSONArray();

            JSONObject calWrite = new JSONObject();
            calWrite.put("update", new JSONObject()
                    .put("name", docRoot + CalibrationFirestoreCodec.COLLECTION_CALIBRATIONS + "/" + profile.getCalibrationId())
                    .put("fields", CalibrationFirestoreCodec.profileToFields(profile)));
            calWrite.put("updateTransforms", new JSONArray().put(new JSONObject()
                    .put("fieldPath", CalibrationFirestoreCodec.FIELD_SERVER_UPDATED_AT)
                    .put("setToServerValue", "REQUEST_TIME")));
            writes.put(calWrite);

            if (audit != null) {
                JSONObject audWrite = new JSONObject();
                audWrite.put("update", new JSONObject()
                        .put("name", docRoot + CalibrationFirestoreCodec.COLLECTION_AUDIT + "/" + audit.getAuditId())
                        .put("fields", CalibrationFirestoreCodec.auditToFields(audit, prefs.getAuthEmail())));
                audWrite.put("currentDocument", new JSONObject().put("exists", false));
                writes.put(audWrite);
            }

            JSONObject body = new JSONObject().put("writes", writes);
            Request req = new Request.Builder()
                    .url(getFirestoreBaseUrl() + ":commit")
                    .addHeader("Authorization", "Bearer " + token)
                    .post(RequestBody.create(body.toString(), JSON_MEDIA))
                    .build();
            try (Response resp = httpClient.newCall(req).execute()) {
                if (resp.isSuccessful()) return null;
                String err = resp.body() != null ? extractFirebaseError(resp.body().string()) : "";
                if (resp.code() == 403) {
                    return "Firebase rejected the change (permission denied). Check that firestore.rules are deployed and this account is an administrator.";
                }
                return "Could not publish (HTTP " + resp.code() + "): " + err;
            }
        } catch (IOException e) {
            return "No connection. Please try again when online.";
        } catch (JSONException e) {
            return "Could not prepare calibration data.";
        }
    }

    public static class CalibrationSyncResult {
        public final boolean success;
        public final List<GlobalCalibrationProfile> changedProfiles;
        public final long newCursorMs;
        public final String message;

        public CalibrationSyncResult(boolean success, List<GlobalCalibrationProfile> changed, long cursor, String message) {
            this.success = success;
            this.changedProfiles = changed != null ? changed : new ArrayList<>();
            this.newCursorMs = cursor;
            this.message = message;
        }
    }

    /**
     * Incremental (delta) sync: downloads only calibration documents whose server-side
     * serverUpdatedAt >= sinceCursorMs, so the full collection is never re-downloaded repeatedly.
     * Deactivated profiles arrive with active=false; removed profiles arrive as deleted=true tombstones.
     */
    public CalibrationSyncResult fetchCalibrationChangesSync(long sinceCursorMs) {
        String token = getCalibrationReadTokenSync();
        if (token == null) {
            return new CalibrationSyncResult(false, null, sinceCursorMs, "No Firebase read credential available");
        }
        List<GlobalCalibrationProfile> changed = new ArrayList<>();
        long cursor = sinceCursorMs;
        try {
            JSONObject structuredQuery = new JSONObject()
                    .put("from", new JSONArray().put(new JSONObject()
                            .put("collectionId", CalibrationFirestoreCodec.COLLECTION_CALIBRATIONS)))
                    .put("where", new JSONObject().put("fieldFilter", new JSONObject()
                            .put("field", new JSONObject().put("fieldPath", CalibrationFirestoreCodec.FIELD_SERVER_UPDATED_AT))
                            .put("op", "GREATER_THAN_OR_EQUAL")
                            .put("value", new JSONObject().put("timestampValue",
                                    CalibrationFirestoreCodec.toRfc3339(sinceCursorMs)))))
                    .put("orderBy", new JSONArray().put(new JSONObject()
                            .put("field", new JSONObject().put("fieldPath", CalibrationFirestoreCodec.FIELD_SERVER_UPDATED_AT))
                            .put("direction", "ASCENDING")))
                    .put("limit", 300);
            JSONObject body = new JSONObject().put("structuredQuery", structuredQuery);

            Request req = new Request.Builder()
                    .url(getFirestoreBaseUrl() + ":runQuery")
                    .addHeader("Authorization", "Bearer " + token)
                    .post(RequestBody.create(body.toString(), JSON_MEDIA))
                    .build();
            try (Response resp = httpClient.newCall(req).execute()) {
                if (!resp.isSuccessful() || resp.body() == null) {
                    return new CalibrationSyncResult(false, null, sinceCursorMs, "Sync failed (HTTP " + resp.code() + ")");
                }
                JSONArray results = new JSONArray(resp.body().string());
                for (int i = 0; i < results.length(); i++) {
                    JSONObject item = results.optJSONObject(i);
                    JSONObject doc = item != null ? item.optJSONObject("document") : null;
                    if (doc == null) continue;
                    JSONObject fields = doc.optJSONObject("fields");
                    GlobalCalibrationProfile p = CalibrationFirestoreCodec.fieldsToProfile(fields);
                    if (p == null) continue;
                    changed.add(p);
                    long serverTs = CalibrationFirestoreCodec.getLong(fields, CalibrationFirestoreCodec.FIELD_SERVER_UPDATED_AT, 0L);
                    if (serverTs > cursor) cursor = serverTs;
                }
            }
            return new CalibrationSyncResult(true, changed, cursor, "Synced " + changed.size() + " calibration change(s)");
        } catch (IOException e) {
            return new CalibrationSyncResult(false, null, sinceCursorMs, "Offline");
        } catch (JSONException e) {
            return new CalibrationSyncResult(false, null, sinceCursorMs, "Malformed sync response");
        }
    }

    /**
     * Loads the most recent administrator audit entries (readable by admins only per firestore.rules).
     */
    public List<CalibrationAuditRecord> fetchRecentAuditLogsSync(int limit) {
        List<CalibrationAuditRecord> list = new ArrayList<>();
        if (!isSignedIn()) return list;
        String token = ensureFreshIdTokenSync();
        try {
            JSONObject structuredQuery = new JSONObject()
                    .put("from", new JSONArray().put(new JSONObject()
                            .put("collectionId", CalibrationFirestoreCodec.COLLECTION_AUDIT)))
                    .put("orderBy", new JSONArray().put(new JSONObject()
                            .put("field", new JSONObject().put("fieldPath", "timestampMs"))
                            .put("direction", "DESCENDING")))
                    .put("limit", Math.max(1, limit));
            Request req = new Request.Builder()
                    .url(getFirestoreBaseUrl() + ":runQuery")
                    .addHeader("Authorization", "Bearer " + token)
                    .post(RequestBody.create(new JSONObject().put("structuredQuery", structuredQuery).toString(), JSON_MEDIA))
                    .build();
            try (Response resp = httpClient.newCall(req).execute()) {
                if (!resp.isSuccessful() || resp.body() == null) return list;
                JSONArray results = new JSONArray(resp.body().string());
                for (int i = 0; i < results.length(); i++) {
                    JSONObject item = results.optJSONObject(i);
                    JSONObject doc = item != null ? item.optJSONObject("document") : null;
                    if (doc == null) continue;
                    CalibrationAuditRecord r = CalibrationFirestoreCodec.fieldsToAudit(doc.optJSONObject("fields"));
                    if (r != null) list.add(r);
                }
            }
        } catch (Exception ignored) {
        }
        return list;
    }

