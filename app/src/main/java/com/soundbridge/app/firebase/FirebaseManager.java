    /**
     * Syncs a single AlertEvent to Cloud Firestore at users/{uid}/alerts/{alertId}
     * and updates liveAlerts/{uid}/{deviceId} in Firebase Realtime Database.
     */
    public void syncAlertToCloud(AlertEvent alert, CompletionCallback callback) {
        if (!isSignedIn()) {
            if (callback != null) {
                mainHandler.post(() -> callback.onComplete(false, "Not signed in to Firebase"));
            }
            return;
        }
        final String uid = prefs.getAuthUid();
        ioExecutor.execute(() -> {
            String idToken = ensureFreshIdTokenSync();
            boolean firestoreOk = writeAlertToFirestoreSync(uid, idToken, alert);
            writeLatestAlertToRealtimeDbSync(uid, idToken, alert);
            if (callback != null) {
                mainHandler.post(() -> callback.onComplete(firestoreOk, firestoreOk ? "Synced to Firestore & RTDB" : "Pending retry"));
            }
        });
    }

    public boolean writeAlertToFirestoreSync(String uid, String idToken, AlertEvent alert) {
        if (isBlank(uid) || isBlank(idToken) || alert == null) return false;
        try {
            String url = getFirestoreBaseUrl() + "/users/" + uid + "/alerts/" + alert.getId();
            JSONObject fields = new JSONObject();
            fields.put("eventId", firestoreString(alert.getId()));
            fields.put("label", firestoreString(alert.getLabel()));
            fields.put("rawModelLabel", firestoreString(alert.getRawModelLabel()));
            fields.put("category", firestoreString(alert.getCategory()));
            fields.put("source", firestoreString(alert.getSource()));
            fields.put("confidence", firestoreDouble(alert.getConfidence()));
            // Recognition audit fields (original ML output vs. final displayed label). Local clip paths are never uploaded.
            fields.put("originalPrediction", firestoreString(alert.getOriginalPrediction()));
            fields.put("originalConfidence", firestoreDouble(alert.getOriginalConfidence()));
            fields.put("recognitionMethod", firestoreString(alert.getRecognitionMethod()));
            fields.put("appliedCalibrationId", firestoreString(alert.getAppliedCalibrationId()));
            fields.put("detectionTimestampMs", firestoreInt(alert.getTimestampMs()));
            fields.put("createdAt", firestoreTimestamp(alert.getTimestampMs()));
            fields.put("deviceId", firestoreString(alert.getDeviceId()));
            fields.put("acknowledged", firestoreBool(alert.isAcknowledged()));
            fields.put("deliveryStatus", firestoreString(alert.getDeliveryStatus()));

            JSONObject doc = new JSONObject();
            doc.put("fields", fields);

            Request req = new Request.Builder()
                    .url(url)
                    .addHeader("Authorization", "Bearer " + idToken)
                    .patch(RequestBody.create(doc.toString(), JSON_MEDIA))
                    .build();
            try (Response resp = httpClient.newCall(req).execute()) {
                return resp.isSuccessful();
            }
        } catch (Exception e) {
            return false;
        }
    }

