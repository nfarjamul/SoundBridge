    public interface AdminCheckCallback {
        void onResult(boolean isAdmin, String message);
    }

    private volatile String lastAdminCheckDiagnostic = "Not verified";

    public String getLastAdminCheckDiagnostic() {
        return lastAdminCheckDiagnostic;
    }

    /**
     * Verifies administrator privileges against Firebase (never against a local flag):
     * 1) Firebase custom claim admin == true / role == "admin" in a freshly refreshed ID token, OR
     * 2) Protected Firestore document adminUsers/{uid} (role == "admin" or isAdmin == true, active != false),
     *    readable only by its owner and writable only via Firebase Console / Admin SDK (see firestore.rules).
     * Must run off the main thread.
     */
    public boolean verifyAdminSync() {
        if (!isSignedIn()) {
            prefs.setAdminVerifiedHint(null, false);
            lastAdminCheckDiagnostic = "Not signed in with a Google account";
            return false;
        }
        String uid = prefs.getAuthUid();
        // Force a refresh so newly granted/revoked custom claims are reflected
        String token = refreshTokenSync(prefs.getAuthRefreshToken(), false);
        if (token == null) {
            token = prefs.getAuthIdToken();
        }
        boolean admin = AdminClaimsParser.hasAdminCustomClaim(token);
        if (admin) {
            lastAdminCheckDiagnostic = "Admin privileges confirmed via custom claim";
        } else {
            try {
                Request req = new Request.Builder()
                        .url(getFirestoreBaseUrl() + "/" + CalibrationFirestoreCodec.COLLECTION_ADMINS + "/" + uid)
                        .addHeader("Authorization", "Bearer " + token)
                        .get()
                        .build();
                try (Response resp = httpClient.newCall(req).execute()) {
                    if (resp.isSuccessful() && resp.body() != null) {
                        JSONObject doc = new JSONObject(resp.body().string());
                        JSONObject fields = doc.optJSONObject("fields");
                        admin = AdminClaimsParser.isAdminUserDocument(fields);
                        if (admin) {
                            lastAdminCheckDiagnostic = "Admin verified via adminUsers/" + uid;
                        } else {
                            lastAdminCheckDiagnostic = "Document adminUsers/" + uid + " found, but requires role == 'admin' and active == true";
                        }
                    } else if (resp.code() == 403) {
                        lastAdminCheckDiagnostic = "Firestore Security Rules blocked read (HTTP 403). Paste firestore.rules into Firebase Console > Firestore > Rules tab.";
                    } else if (resp.code() == 404) {
                        lastAdminCheckDiagnostic = "Document not found at collection 'adminUsers' with Document ID '" + uid + "'.";
                    } else {
                        lastAdminCheckDiagnostic = "Firestore error: HTTP " + resp.code();
                    }
                }
            } catch (Exception e) {
                lastAdminCheckDiagnostic = "Network error: " + e.getMessage();
                admin = false;
            }
        }
        prefs.setAdminVerifiedHint(uid, admin);
        return admin;
    }

    public void verifyAdminAsync(AdminCheckCallback callback) {
        ioExecutor.execute(() -> {
            boolean admin = verifyAdminSync();
            if (callback != null) {
                String message = lastAdminCheckDiagnostic;
                mainHandler.post(() -> callback.onResult(admin, message));
            }
        });
    }

