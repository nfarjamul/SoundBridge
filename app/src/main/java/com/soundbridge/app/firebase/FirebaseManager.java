    /**
     * Checks resources generated by com.google.gms.google-services plugin from app/google-services.json,
     * or an optional assets/google-services.json file if provided by the developer.
     */
    public final void detectFirebaseConfiguration() {
        projectId = getStringResourceByName("project_id");
        apiKey = getStringResourceByName("google_api_key");
        appId = getStringResourceByName("google_app_id");
        databaseUrl = getStringResourceByName("firebase_database_url");
        webClientId = getStringResourceByName("default_web_client_id");

        if (isBlank(projectId) || isBlank(apiKey) || isBlank(appId)) {
            // Also check if user placed google-services.json in assets for easy inspection
            try (InputStream is = appContext.getAssets().open("google-services.json")) {
                byte[] buf = new byte[is.available()];
                int read = is.read(buf);
                if (read > 0) {
                    JSONObject root = new JSONObject(new String(buf, 0, read, StandardCharsets.UTF_8));
                    JSONObject projectInfo = root.optJSONObject("project_info");
                    if (projectInfo != null) {
                        projectId = projectInfo.optString("project_id", projectId);
                        databaseUrl = projectInfo.optString("firebase_url", databaseUrl);
                    }
                    JSONArray clients = root.optJSONArray("client");
                    if (clients != null && clients.length() > 0) {
                        JSONObject client0 = clients.getJSONObject(0);
                        JSONObject clientInfo = client0.optJSONObject("client_info");
                        if (clientInfo != null) {
                            appId = clientInfo.optString("mobilesdk_app_id", appId);
                        }
                        JSONArray apiKeys = client0.optJSONArray("api_key");
                        if (apiKeys != null && apiKeys.length() > 0) {
                            apiKey = apiKeys.getJSONObject(0).optString("current_key", apiKey);
                        }
                        JSONArray oauthClients = client0.optJSONArray("oauth_client");
                        if (oauthClients != null) {
                            for (int i = 0; i < oauthClients.length(); i++) {
                                JSONObject oc = oauthClients.getJSONObject(i);
                                if (oc.optInt("client_type") == 3) {
                                    webClientId = oc.optString("client_id", webClientId);
                                    break;
                                }
                            }
                        }
                    }
                }
            } catch (Exception ignored) {
            }
        }

        if ( !isBlank(projectId) && isBlank(databaseUrl)) {
            databaseUrl = "https://" + projectId + "-default-rtdb.firebaseio.com";
        }
        configured = !isBlank(projectId) && !isBlank(apiKey) && !isBlank(appId)
                && !projectId.contains("placeholder") && !apiKey.contains("placeholder");
    }

