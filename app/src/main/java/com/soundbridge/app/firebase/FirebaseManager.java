    private static JSONObject firestoreTimestamp(long epochMs) throws JSONException {
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US);
        sdf.setTimeZone(TimeZone.getTimeZone("UTC"));
        JSONObject o = new JSONObject();
        o.put("timestampValue", sdf.format(new Date(epochMs)));
        return o;
    }

    private String getStringResourceByName(String resName) {
        try {
            Resources res = appContext.getResources();
            int id = res.getIdentifier(resName, "string", appContext.getPackageName());
            if (id != 0) {
                return res.getString(id);
            }
        } catch (Exception ignored) {
        }
        return null;
    }

    private static String extractFirebaseError(String body) {
        try {
            JSONObject obj = new JSONObject(body);
            JSONObject err = obj.optJSONObject("error");
            if (err != null) {
                return err.optString("message", body);
            }
        } catch (Exception ignored) {
        }
        return body != null && !body.isEmpty() ? body : "Unknown error";
    }

