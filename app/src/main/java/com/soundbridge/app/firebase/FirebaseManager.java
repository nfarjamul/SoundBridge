    /**
     * Authenticates with Firebase Authentication using a Google ID Token obtained from Google Sign-In.
     * On success, creates/updates users/{uid} in Cloud Firestore and presence/{uid}/{deviceId} in RTDB.
     */
    public void authenticateWithGoogleIdToken(String googleIdToken, AuthCallback callback) {
        if (!configured) {
            postAuthError(callback, getConfigurationDiagnosticSummary());
            return;
        }
        if (isBlank(googleIdToken)) {
            postAuthError(callback, "Google ID token was empty or sign-in was cancelled.");
            return;
        }

        ioExecutor.execute(() -> {
            try {
                String url = "https://identitytoolkit.googleapis.com/v1/accounts:signInWithIdp?key=" + apiKey;
                JSONObject payload = new JSONObject();
                payload.put("postBody", "id_token=" + googleIdToken + "&providerId=google.com");
                payload.put("requestUri", "http://localhost");
                payload.put("returnIdpCredential", true);
                payload.put("returnSecureToken", true);

                Request req = new Request.Builder()
                        .url(url)
                        .post(RequestBody.create(payload.toString(), JSON_MEDIA))
                        .build();

                try (Response resp = httpClient.newCall(req).execute()) {
                    String bodyStr = resp.body() != null ? resp.body().string() : "";
                    if (!resp.isSuccessful()) {
                        postAuthError(callback, "Firebase Auth rejected Google credential (HTTP " + resp.code() + "): " + extractFirebaseError(bodyStr));
                        return;
                    }
                    JSONObject json = new JSONObject(bodyStr);
                    String uid = json.optString("localId", "");
                    String idToken = json.optString("idToken", "");
                    String email = json.optString("email", "");
                    String displayName = json.optString("displayName", email);
                    String photoUrl = json.optString("photoUrl", "");

                    if (isBlank(uid) || isBlank(idToken)) {
                        postAuthError(callback, "Firebase Auth response did not include a valid UID/idToken.");
                        return;
                    }

                    prefs.saveAuthenticatedUser(uid, email, displayName, idToken);
                    prefs.saveAuthTokens(idToken, json.optString("refreshToken", ""), json.optLong("expiresIn", 3600L));
                    prefs.setAdminVerifiedHint(null, false);
                    upsertUserProfileInFirestoreSync(uid, idToken, displayName, email, photoUrl);
                    updatePresenceInRealtimeDatabase(true, false, 100);

                    mainHandler.post(() -> callback.onSuccess(uid, email, displayName));
                }
            } catch (IOException e) {
                postAuthError(callback, "Network error during Firebase Google authentication: " + e.getMessage());
            } catch (JSONException e) {
                postAuthError(callback, "Invalid response format from Firebase Auth: " + e.getMessage());
            }
        });
    }

