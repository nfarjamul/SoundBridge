    /**
     * Returns a valid (non-expired) Firebase ID token for the signed-in user, refreshing it through
     * securetoken.googleapis.com when it is within 2 minutes of expiry. Must run off the main thread.
     */
    public synchronized String ensureFreshIdTokenSync() {
        String idToken = prefs.getAuthIdToken();
        if (!configured || isBlank(idToken)) return idToken;
        long expiry = prefs.getAuthTokenExpiryMs();
        if (expiry <= 0L) {
            expiry = AdminClaimsParser.getTokenExpiryMs(idToken);
        }
        if (expiry > System.currentTimeMillis() + 120_000L) {
            return idToken;
        }
        String refreshed = refreshTokenSync(prefs.getAuthRefreshToken(), false);
        return refreshed != null ? refreshed : idToken;
    }

    private String refreshTokenSync(String refreshToken, boolean anonymousSession) {
        if (isBlank(refreshToken)) return null;
        try {
            String url = "https://securetoken.googleapis.com/v1/token?key=" + apiKey;
            RequestBody body = new okhttp3.FormBody.Builder()
                    .add("grant_type", "refresh_token")
                    .add("refresh_token", refreshToken)
                    .build();
            Request req = new Request.Builder().url(url).post(body).build();
            try (Response resp = httpClient.newCall(req).execute()) {
                if (!resp.isSuccessful() || resp.body() == null) return null;
                JSONObject json = new JSONObject(resp.body().string());
                String newId = json.optString("id_token", "");
                String newRefresh = json.optString("refresh_token", refreshToken);
                long expiresIn = json.optLong("expires_in", 3600L);
                if (isBlank(newId)) return null;
                if (anonymousSession) {
                    prefs.saveAnonymousCalibrationSession(newId, newRefresh, expiresIn);
                } else {
                    prefs.saveAuthTokens(newId, newRefresh, expiresIn);
                }
                return newId;
            }
        } catch (Exception e) {
            return null;
        }
    }

    /**
     * Token used for READING global calibrations. Signed-in users use their own token; users who chose
     * "Continue without an account" use an optional Firebase Anonymous Auth session (if the Anonymous
     * provider is enabled in Firebase Console). Returns null if no read credential is available.
     */
    private String getCalibrationReadTokenSync() {
        if (!configured) return null;
        if (isSignedIn()) return ensureFreshIdTokenSync();

        String anonToken = prefs.getAnonymousCalibrationIdToken();
        if (!isBlank(anonToken) && prefs.getAnonymousCalibrationExpiryMs() > System.currentTimeMillis() + 120_000L) {
            return anonToken;
        }
        String refreshed = refreshTokenSync(prefs.getAnonymousCalibrationRefreshToken(), true);
        if (refreshed != null) return refreshed;

        try {
            String url = "https://identitytoolkit.googleapis.com/v1/accounts:signUp?key=" + apiKey;
            JSONObject payload = new JSONObject().put("returnSecureToken", true);
            Request req = new Request.Builder()
                    .url(url)
                    .post(RequestBody.create(payload.toString(), JSON_MEDIA))
                    .build();
            try (Response resp = httpClient.newCall(req).execute()) {
                if (!resp.isSuccessful() || resp.body() == null) return null;
                JSONObject json = new JSONObject(resp.body().string());
                String idToken = json.optString("idToken", "");
                if (isBlank(idToken)) return null;
                prefs.saveAnonymousCalibrationSession(idToken, json.optString("refreshToken", ""), json.optLong("expiresIn", 3600L));
                return idToken;
            }
        } catch (Exception e) {
            return null;
        }
    }

